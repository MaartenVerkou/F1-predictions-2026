const POSTGRES_SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  created_at TEXT NOT NULL,
  is_verified INTEGER NOT NULL DEFAULT 0,
  verified_at TEXT,
  is_admin INTEGER NOT NULL DEFAULT 0,
  is_simulated INTEGER NOT NULL DEFAULT 0,
  hide_from_global INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS groups (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  owner_id INTEGER NOT NULL,
  created_at TEXT NOT NULL,
  join_code TEXT,
  join_password_hash TEXT,
  is_public INTEGER NOT NULL DEFAULT 0,
  is_global INTEGER NOT NULL DEFAULT 0,
  rules_text TEXT,
  is_simulated INTEGER NOT NULL DEFAULT 0,
  invite_link_open INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS group_members (
  user_id INTEGER NOT NULL,
  group_id INTEGER NOT NULL,
  role TEXT NOT NULL,
  joined_at TEXT NOT NULL,
  coupled_to_global INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY(user_id, group_id)
);

CREATE TABLE IF NOT EXISTS invites (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id INTEGER NOT NULL,
  code TEXT NOT NULL UNIQUE,
  created_at TEXT NOT NULL,
  created_by INTEGER NOT NULL,
  expires_at TEXT
);

CREATE TABLE IF NOT EXISTS responses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  group_id INTEGER NOT NULL,
  question_id TEXT NOT NULL,
  answer TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE(user_id, group_id, question_id)
);

CREATE TABLE IF NOT EXISTS guest_responses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guest_id TEXT NOT NULL,
  group_id INTEGER NOT NULL,
  question_id TEXT NOT NULL,
  answer TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE(guest_id, group_id, question_id)
);

CREATE TABLE IF NOT EXISTS named_guest_profiles (
  guest_id TEXT PRIMARY KEY,
  display_name TEXT NOT NULL,
  source_group_id INTEGER,
  resume_token_hash TEXT,
  claim_secret_hash TEXT,
  claim_secret_mode TEXT,
  claim_secret_prompt TEXT,
  claim_secret_set_at TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS named_guest_group_members (
  group_id INTEGER NOT NULL,
  guest_id TEXT NOT NULL,
  display_name TEXT NOT NULL,
  joined_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  PRIMARY KEY(group_id, guest_id)
);

CREATE TABLE IF NOT EXISTS actuals (
  question_id TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS seasons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  year INTEGER NOT NULL UNIQUE,
  label TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS drivers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  given_name TEXT NOT NULL,
  family_name TEXT NOT NULL,
  display_name TEXT NOT NULL,
  driver_code TEXT,
  nationality_code TEXT,
  date_of_birth TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS teams (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  display_name TEXT NOT NULL,
  short_name TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS races (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id INTEGER NOT NULL,
  round_number INTEGER NOT NULL,
  slug TEXT NOT NULL,
  display_name TEXT NOT NULL,
  scheduled_date TEXT,
  scheduled_timezone TEXT,
  calendar_state TEXT NOT NULL DEFAULT 'scheduled',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE(season_id, round_number),
  UNIQUE(season_id, slug)
);

CREATE TABLE IF NOT EXISTS season_drivers (
  season_id INTEGER NOT NULL,
  driver_id INTEGER NOT NULL,
  driver_number TEXT,
  display_name_override TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  PRIMARY KEY(season_id, driver_id)
);

CREATE TABLE IF NOT EXISTS season_teams (
  season_id INTEGER NOT NULL,
  team_id INTEGER NOT NULL,
  display_name_override TEXT,
  display_order INTEGER NOT NULL DEFAULT 0,
  order_basis TEXT NOT NULL DEFAULT 'manual',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  PRIMARY KEY(season_id, team_id)
);

CREATE TABLE IF NOT EXISTS driver_team_assignments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id INTEGER NOT NULL,
  driver_id INTEGER NOT NULL,
  team_id INTEGER NOT NULL,
  from_round INTEGER NOT NULL,
  to_round INTEGER,
  seat_number INTEGER NOT NULL DEFAULT 1,
  source TEXT NOT NULL DEFAULT 'admin',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE(season_id, driver_id, from_round)
);

CREATE INDEX IF NOT EXISTS idx_driver_team_assignments_lookup
  ON driver_team_assignments(season_id, driver_id, from_round, to_round);

CREATE INDEX IF NOT EXISTS idx_driver_team_assignments_seat_lookup
  ON driver_team_assignments(season_id, team_id, seat_number, from_round, to_round);

CREATE INDEX IF NOT EXISTS idx_season_drivers_driver_lookup
  ON season_drivers(driver_id, season_id);

CREATE INDEX IF NOT EXISTS idx_season_teams_team_lookup
  ON season_teams(team_id, season_id);

CREATE TABLE IF NOT EXISTS entity_aliases (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type TEXT NOT NULL,
  entity_id INTEGER NOT NULL,
  season_id INTEGER,
  alias TEXT NOT NULL,
  normalized_alias TEXT NOT NULL,
  source TEXT NOT NULL DEFAULT 'admin',
  created_at TEXT NOT NULL,
  UNIQUE(entity_type, season_id, normalized_alias)
);

CREATE INDEX IF NOT EXISTS idx_entity_aliases_lookup
  ON entity_aliases(entity_type, season_id, normalized_alias);

CREATE TABLE IF NOT EXISTS entity_provider_refs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type TEXT NOT NULL,
  entity_id INTEGER NOT NULL,
  provider TEXT NOT NULL,
  provider_key TEXT NOT NULL,
  provider_label TEXT,
  created_at TEXT NOT NULL,
  UNIQUE(provider, provider_key),
  UNIQUE(entity_type, entity_id, provider)
);

CREATE TABLE IF NOT EXISTS actual_snapshots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season INTEGER NOT NULL,
  round_number INTEGER,
  round_name TEXT,
  label TEXT NOT NULL,
  source_type TEXT NOT NULL,
  source_note TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  created_by_user_id INTEGER,
  review_status TEXT NOT NULL DEFAULT 'reviewed',
  reviewed_at TEXT,
  reviewed_by_user_id INTEGER,
  source_data_import_id INTEGER,
  source_data_snapshot_id INTEGER
);

CREATE TABLE IF NOT EXISTS race_data_imports (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season INTEGER NOT NULL,
  sync_id TEXT NOT NULL UNIQUE,
  status TEXT NOT NULL,
  source_type TEXT NOT NULL,
  parser_version TEXT NOT NULL,
  started_at TEXT NOT NULL,
  completed_at TEXT,
  requested_rounds INTEGER NOT NULL DEFAULT 0,
  completed_rounds INTEGER NOT NULL DEFAULT 0,
  reconstructed INTEGER NOT NULL DEFAULT 0,
  source_note TEXT,
  error_message TEXT
);

CREATE INDEX IF NOT EXISTS idx_race_data_imports_season_started
  ON race_data_imports(season, started_at);

CREATE TABLE IF NOT EXISTS race_data_snapshots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  import_id INTEGER,
  season INTEGER NOT NULL,
  round_number INTEGER NOT NULL,
  round_name TEXT,
  sync_id TEXT NOT NULL,
  fetched_at TEXT NOT NULL,
  source_type TEXT NOT NULL,
  source_note TEXT,
  parser_version TEXT NOT NULL DEFAULT 'evidence-v1',
  calendar_state TEXT NOT NULL DEFAULT 'completed',
  reconstructed INTEGER NOT NULL DEFAULT 0,
  coverage_status TEXT NOT NULL,
  payload_json TEXT NOT NULL,
  created_at TEXT NOT NULL,
  UNIQUE(season, round_number, sync_id)
);

CREATE INDEX IF NOT EXISTS idx_race_data_snapshots_season_round
  ON race_data_snapshots(season, round_number, created_at);
CREATE INDEX IF NOT EXISTS idx_race_data_snapshots_import
  ON race_data_snapshots(import_id, round_number);

CREATE TABLE IF NOT EXISTS actual_snapshot_values (
  snapshot_id INTEGER NOT NULL,
  question_id TEXT NOT NULL,
  value TEXT NOT NULL,
  PRIMARY KEY(snapshot_id, question_id)
);

CREATE INDEX IF NOT EXISTS idx_actual_snapshots_season_round
  ON actual_snapshots(season, round_number, created_at);
CREATE INDEX IF NOT EXISTS idx_actual_snapshot_values_snapshot
  ON actual_snapshot_values(snapshot_id);

CREATE TABLE IF NOT EXISTS question_settings (
  question_id TEXT PRIMARY KEY,
  included INTEGER NOT NULL DEFAULT 1,
  points_override TEXT,
  order_index INTEGER,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS email_verifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  token_hash TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS password_resets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS pending_guest_claims (
  user_id INTEGER PRIMARY KEY,
  guest_id TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS named_guest_recovery_tokens (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guest_id TEXT NOT NULL,
  group_id INTEGER NOT NULL,
  token_hash TEXT NOT NULL UNIQUE,
  action TEXT NOT NULL,
  target_email TEXT NOT NULL,
  target_user_id INTEGER,
  created_by_user_id INTEGER NOT NULL,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  used_at TEXT,
  CHECK(action IN ('transfer', 'reset_secret'))
);

CREATE TABLE IF NOT EXISTS admin_ideas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL DEFAULT 'question',
  title TEXT NOT NULL,
  notes TEXT,
  status TEXT NOT NULL DEFAULT 'open',
  seed_key TEXT UNIQUE,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  created_by_user_id INTEGER,
  updated_by_user_id INTEGER,
  CHECK(type IN ('question', 'feature', 'other')),
  CHECK(status IN ('open', 'resolved', 'ignored'))
);

CREATE INDEX IF NOT EXISTS idx_admin_ideas_status_updated
  ON admin_ideas(status, updated_at);
`;

function ensurePostgresSchema(db) {
  db.exec(POSTGRES_SCHEMA_SQL);
  db.exec("ALTER TABLE drivers ADD COLUMN IF NOT EXISTS driver_code TEXT");
  db.exec("ALTER TABLE drivers ADD COLUMN IF NOT EXISTS nationality_code TEXT");
  db.exec("ALTER TABLE drivers ADD COLUMN IF NOT EXISTS date_of_birth TEXT");
}

module.exports = {
  APP_TABLES,
  IDENTITY_TABLES,
  POSTGRES_SCHEMA_SQL,
  ensurePostgresSchema
};
